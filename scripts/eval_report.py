"""Eval results in one place, and the README's results tables kept in sync.

The JSON files under evals/results/ are the source of truth (they're in git).
The README's tables between <!-- results:start --> and <!-- results:end -->
are generated from the files for the CURRENT versions in the code
(SEARCH_VERSION, PROMPT_VERSION, CACHE_VERSION), so they always describe the
code as it is. CI runs --check-readme.

Usage:
    uv run python -m scripts.eval_report                  # latest results, from the files
    uv run python -m scripts.eval_report --write-readme   # regenerate the README tables
    uv run python -m scripts.eval_report --check-readme   # fail if they're out of date
    uv run python -m scripts.eval_report --import         # add saved files to eval_runs (once)
    uv run python -m scripts.eval_report --history        # every recorded run (eval_runs)
"""

import argparse
import json
import sys
from pathlib import Path

from agent.prompts import PROMPT_VERSION
from core.cache import CACHE_VERSION
from core.search import SEARCH_VERSION

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "evals" / "results"
README = ROOT / "README.md"
START, END = "<!-- results:start -->", "<!-- results:end -->"
KINDS = {"retrieval": "retrieval", "answers": "answers", "cache": "cache"}


def load(kind: str, name: str, results: Path = RESULTS) -> dict:
    return json.loads((results / kind / f"{name}.json").read_text(encoding="utf-8"))


def all_files(results: Path = RESULTS) -> list[tuple[str, Path]]:
    return [
        (kind, p) for kind in KINDS for p in sorted((results / kind).glob("*.json"))
    ]


# --- The README block ---------------------------------------------------------------


def _pct(x: float) -> str:
    return f"{x:.2f}"


def render_results(
    results: Path = RESULTS,
    search: str = SEARCH_VERSION,
    prompt: str = PROMPT_VERSION,
    cache: str = CACHE_VERSION,
) -> str:
    """The generated markdown between the README markers."""
    r = load("retrieval", search, results)
    a = load("answers", prompt, results)
    c_main = load("cache", cache, results)
    c_held = load("cache", f"{cache}-heldout", results)
    names = {"bm25": "BM25 alone", "vector": "Vector alone", "hybrid": "Hybrid (RRF)"}
    best = max(r["rates"], key=lambda m: r["rates"][m]["overall"]["hit@5"])

    lines = [
        START,
        (
            "<!-- Generated by `uv run python -m scripts.eval_report --write-readme`. "
            "Don't edit by hand. -->"
        ),
        "",
        (
            f"**Retrieval**: {r['questions']} hand-labelled questions "
            f"(search `{r['search_version']}`, labels v{r.get('labels', '1')}, "
            f"{r['measured_at'][:10]})"
        ),
        "",
        "| | hit@5 | hit@1 | MRR | near-miss: right Life first |",
        "|---|---|---|---|---|",
    ]
    for method, rates in r["rates"].items():
        o, nm = rates["overall"], rates["by_category"]["near_miss"]
        label = f"**{names[method]}**" if method == best else names[method]
        lines.append(
            f"| {label} | {_pct(o['hit@5'])} | {_pct(o['hit@1'])} | {_pct(o['mrr'])} "
            f"| {_pct(nm['life@1'])} |"
        )
    ar = a["rates"]
    answerable = sum(1 for x in a["results"] if x["category"] != "unanswerable")
    unanswerable = a["questions"] - answerable
    lines += [
        "",
        (
            f"**Answers**: {a['model'].split('/')[-1]}, prompt `{a['prompt_version']}`, "
            f"over `{a['search_version']}` ({a['measured_at'][:10]})"
        ),
        "",
        "| | |",
        "|---|---|",
        f"| answered ({answerable} answerable questions) | {_pct(ar['answered'])} |",
        f"| cites an expected passage | {_pct(ar['cites_expected'])} |",
        (
            f"| main citation from the right Life | {_pct(ar['right_life'])} "
            f"(near-miss {_pct(a['by_category']['near_miss']['right_life'])}) |"
        ),
        f"| declined ({unanswerable} unanswerable questions) | {_pct(ar['declined'])} |",
        f"| cost for {a['questions']} questions | ${a['cost_usd']:.4f} |",
        "",
        (
            f"**Semantic cache**: gate `{c_main['cache_version']}` (hit at >= "
            f"{c_main['hit_at']}, miss below {c_main['miss_below']}, judge "
            f"`{c_main['judge_prompt_version']}`)"
        ),
        "",
        "| | main pairs | held-out pairs |",
        "|---|---|---|",
        f"| pairs | {c_main['pairs']} | {c_held['pairs']} |",
        (
            f"| **false hits** (a wrong answer served) | **{c_main['false_hits']}** "
            f"| **{c_held['false_hits']}** |"
        ),
        (
            f"| true paraphrases served from the cache | "
            f"{_pct(c_main['hit_rate_on_paraphrases'])} | "
            f"{_pct(c_held['hit_rate_on_paraphrases'])} |"
        ),
        f"| judge calls | {c_main['judge_calls']} | {c_held['judge_calls']} |",
        END,
    ]
    return "\n".join(lines)


def replace_block(text: str, block: str) -> str:
    if START not in text or END not in text:
        raise ValueError(f"README needs {START} and {END} markers")
    before, rest = text.split(START, 1)
    _, after = rest.split(END, 1)
    return before + block + after


# --- Database (eval_runs) -------------------------------------------------------------


def import_files() -> int:
    from core.eval_records import record_run

    added = 0
    for kind, path in all_files():
        report = json.loads(path.read_text(encoding="utf-8"))
        if record_run(kind, report, path, with_git=False):
            added += 1
    return added


def history() -> int:
    from core.db import connect

    with connect("eval") as conn:
        rows = conn.execute(
            "select kind, versions, pair_set, rates, cost_usd, left(git_commit, 7) as git,"
            " git_dirty, measured_at from eval_runs order by measured_at"
        ).fetchall()
    for r in rows:
        v = r["versions"]
        version = (
            v.get("search_version")
            if r["kind"] == "retrieval"
            else v.get("prompt_version")
            if r["kind"] == "answers"
            else v.get("cache_version")
        )
        dirty = "*" if r["git_dirty"] else ""
        print(
            f"{r['measured_at']:%Y-%m-%d %H:%M}  {r['kind']:<9} {version or '?':<16}"
            f" {r['pair_set']:<8} labels {v.get('labels', '?'):<3}"
            f" ${float(r['cost_usd'] or 0):.4f}  {r['git'] or '-'}{dirty}"
        )
    print(f"\n{len(rows)} runs (* = uncommitted changes when run)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--write-readme", action="store_true")
    group.add_argument("--check-readme", action="store_true")
    group.add_argument("--import", dest="import_", action="store_true")
    group.add_argument("--history", action="store_true")
    args = parser.parse_args()

    if args.import_:
        print(f"Added {import_files()} run(s) to eval_runs.")
        return 0
    if args.history:
        return history()

    block = render_results()
    readme = README.read_text(encoding="utf-8")
    if args.write_readme:
        README.write_text(replace_block(readme, block), encoding="utf-8", newline="\n")
        print("README results updated.")
        return 0
    if args.check_readme:
        if replace_block(readme, block) != readme:
            print(
                "README results are out of date. Run:"
                " uv run python -m scripts.eval_report --write-readme",
                file=sys.stderr,
            )
            return 1
        print("README results match the saved eval results.")
        return 0
    print(block)
    return 0


if __name__ == "__main__":
    sys.exit(main())
